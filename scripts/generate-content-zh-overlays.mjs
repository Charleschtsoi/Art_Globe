/* global process */
import fs from 'node:fs/promises'
import path from 'node:path'

const EXTERNAL_PATH = path.resolve(process.cwd(), 'src/data/externalArtData.json')
const OUTPUT_PATH = path.resolve(process.cwd(), 'src/i18n/contentZhHantGenerated.js')
const LIMIT = Number(process.env.ZH_OVERLAY_LIMIT ?? 3000)

const ARTIST_ZH = new Map([
  ['johannes vermeer', '約翰尼斯・維梅爾'],
  ['pieter bruegel', '彼得・布勒哲爾'],
  ['francisco goya', '法蘭西斯科・哥雅'],
  ['pablo picasso', '巴勃羅・畢卡索'],
  ['andrei rublev', '安德烈・魯布列夫'],
  ['marc chagall', '馬克・夏卡爾'],
  ['mikhail vrubel', '米哈伊爾・弗魯貝爾'],
  ['eugène louis boudin', '歐仁・路易・布丹']
])

const COUNTRY_ZH = new Map([
  ['china', '中國'],
  ['japan', '日本'],
  ['france', '法國'],
  ['italy', '義大利'],
  ['spain', '西班牙'],
  ['netherlands', '荷蘭'],
  ['germany', '德國'],
  ['united kingdom', '英國'],
  ['united states', '美國'],
  ['canada', '加拿大'],
  ['australia', '澳洲'],
  ['new zealand', '紐西蘭'],
  ['india', '印度'],
  ['egypt', '埃及'],
  ['south africa', '南非'],
  ['russia', '俄羅斯']
])

function wrapTitle(title) {
  const raw = String(title ?? '').trim()
  if (!raw || raw.toLowerCase() === 'untitled') return '無題'
  if (/[\u3400-\u9FFF]/u.test(raw)) return raw
  return `《${raw}》`
}

function mapArtist(artist) {
  const raw = String(artist ?? '').trim()
  if (!raw) return '未知藝術家'
  const mapped = ARTIST_ZH.get(raw.toLowerCase())
  return mapped || raw
}

function mapCountry(country) {
  const raw = String(country ?? '').trim()
  if (!raw) return ''
  return COUNTRY_ZH.get(raw.toLowerCase()) || raw
}

async function main() {
  const raw = await fs.readFile(EXTERNAL_PATH, 'utf8')
  const list = JSON.parse(raw)
  if (!Array.isArray(list)) throw new Error('externalArtData.json must be an array')

  const rows = list.slice(0, LIMIT)
  const out = {}
  for (const art of rows) {
    const id = String(art.id ?? art.artwork_id ?? '')
    if (!id) continue
    const title = wrapTitle(art.title)
    const artist = mapArtist(art.artist)
    const museum = String(art.museumName ?? art.current_location?.museum ?? '').trim()
    const city = String(art.current_location?.city ?? '').trim()
    const country = mapCountry(art.current_location?.country ?? '')

    const place = [museum, city, country].filter(Boolean).join('，')
    const description = place
      ? `此作品現藏於${place}。`
      : `此作品為${artist}之作。`

    out[id] = { title, artist, description }
  }

  const body =
    '/**\n' +
    ' * Auto-generated/expandable Traditional Chinese overlays.\n' +
    ' * Generated by scripts/generate-content-zh-overlays.mjs.\n' +
    ' *\n' +
    ' * Keep curated entries in contentZhHant.js for high-quality manual translation.\n' +
    ' */\n' +
    `export const CONTENT_ZH_HANT_GENERATED_BY_ID = ${JSON.stringify(out, null, 2)}\n`

  await fs.writeFile(OUTPUT_PATH, body, 'utf8')
  console.log(`Generated zh overlays: ${Object.keys(out).length}`)
  console.log(`Output: ${path.relative(process.cwd(), OUTPUT_PATH)}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})

